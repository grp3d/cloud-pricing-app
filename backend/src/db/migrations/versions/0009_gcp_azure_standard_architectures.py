import json
import uuid
from collections.abc import Sequence
from decimal import Decimal
from pathlib import Path

import sqlalchemy as sa
from alembic import op
from sqlalchemy.dialects.postgresql import JSONB

# revision identifiers, used by Alembic.
revision: str = '9b4e2c7a1d05'
down_revision: str | Sequence[str] | None = '6c3e9a1b5f08'
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

SEED_DIR = Path(__file__).resolve().parents[2] / "seed"
PROVIDERS = ("gcp", "azure")


def _seed(provider: str) -> dict:
    return json.loads((SEED_DIR / f"standard_architectures_{provider}.json").read_text())


def insert_standard_architectures(connection) -> None:
    """Insert every seeded GCP and Azure architecture the Admin doesn't already own (by name and
    provider, among non-deleted architectures). `clock_timestamp()` keeps each row's
    `created_at` distinct and increasing, so services display in the seed's order (as 0005)."""
    admin_id = connection.execute(
        sa.text("SELECT id FROM users WHERE is_default_admin LIMIT 1")
    ).scalar_one_or_none()
    if admin_id is None:
        return

    for provider in PROVIDERS:
        for architecture in _seed(provider)["architectures"]:
            exists = connection.execute(
                sa.text(
                    "SELECT 1 FROM architectures WHERE user_id = :owner AND name = :name "
                    "AND provider = :provider AND deleted_at IS NULL"
                ).bindparams(owner=admin_id, name=architecture["name"], provider=provider)
            ).first()
            if exists is not None:
                continue

            architecture_id = uuid.uuid4()
            connection.execute(
                sa.text(
                    "INSERT INTO architectures (id, user_id, provider, name, is_public, "
                    "created_at, updated_at) VALUES (:id, :owner, :provider, :name, true, "
                    "clock_timestamp(), clock_timestamp())"
                ).bindparams(
                    id=architecture_id, owner=admin_id, provider=provider,
                    name=architecture["name"],
                )
            )
            ref_to_id: dict[str, uuid.UUID] = {}
            for collection in architecture["collections"]:
                collection_id = uuid.uuid4()
                ref_to_id[collection["ref"]] = collection_id
                connection.execute(
                    sa.text(
                        "INSERT INTO collections (id, architecture_id, type, name, region, "
                        "parent_collection_id, created_at, updated_at) VALUES (:id, "
                        ":architecture, :type, :name, :region, :parent, clock_timestamp(), "
                        "clock_timestamp())"
                    ).bindparams(
                        id=collection_id,
                        architecture=architecture_id,
                        type=collection["type"],
                        name=collection["name"],
                        region=collection["region"],
                        parent=ref_to_id.get(collection["parent_ref"]),
                    )
                )
                for selection in collection["sku_selections"]:
                    connection.execute(
                        sa.text(
                            "INSERT INTO sku_selections (id, collection_id, service_code, sku, "
                            "pricing_term, purchase_option, usage_quantity, provider_options, "
                            "created_at, updated_at) VALUES (:id, :collection, :service_code, "
                            ":sku, :pricing_term, :purchase_option, :usage_quantity, "
                            ":provider_options, clock_timestamp(), clock_timestamp())"
                        ).bindparams(
                            sa.bindparam("provider_options", type_=JSONB),
                            id=uuid.uuid4(),
                            collection=collection_id,
                            service_code=selection["service_code"],
                            sku=selection["sku"],
                            pricing_term=selection["pricing_term"],
                            purchase_option=selection["purchase_option"],
                            usage_quantity=Decimal(str(selection["usage_quantity"])),
                            provider_options=selection.get("provider_options"),
                        )
                    )


def upgrade() -> None:
    """Upgrade schema."""
    insert_standard_architectures(op.get_bind())


def downgrade() -> None:
    """Downgrade schema: remove only the Admin's GCP and Azure architectures with the seeded
    names (never the AWS four, which share the names)."""
    names = sorted({a["name"] for p in PROVIDERS for a in _seed(p)["architectures"]})
    owned = (
        "SELECT a.id FROM architectures a JOIN users u ON u.id = a.user_id "
        "WHERE u.is_default_admin AND a.provider IN ('gcp', 'azure') AND a.name = ANY(:names)"
    )
    op.execute(
        sa.text(
            "DELETE FROM sku_selections WHERE collection_id IN "
            f"(SELECT id FROM collections WHERE architecture_id IN ({owned}))"
        ).bindparams(names=names)
    )
    op.execute(
        sa.text(f"DELETE FROM collections WHERE architecture_id IN ({owned})").bindparams(names=names)
    )
    op.execute(sa.text(f"DELETE FROM architectures WHERE id IN ({owned})").bindparams(names=names))
